def _sync_operation(
    rule_id: UUID,
    payload: dict[str, object],
    *,
    command: str,
    base_version: int | None,
    operation_id: UUID | None = None,
) -> dict[str, object]:
    return {
        "operation_id": str(operation_id or uuid4()),
        "local_sequence": 1,
        "entity_type": "recurring_rule",
        "entity_id": str(rule_id),
        "command": command,
        "base_server_version": base_version,
        "payload": payload,
    }


def _push(client: APIClient, operation: dict[str, object]):
    return client.post(
        "/api/v1/sync/push",
        {"protocol_version": 1, "operations": [operation]},
        format="json",
    )


def test_calendar_schedule_preserves_anchors_and_resolves_dst() -> None:
    spring = scheduled_utc(date(2026, 3, 29), time(2, 30), "Europe/Tirane")
    assert spring == datetime(2026, 3, 29, 1, 0, tzinfo=UTC)
    autumn = scheduled_utc(date(2026, 10, 25), time(2, 30), "Europe/Tirane")
    assert autumn == datetime(2026, 10, 25, 0, 30, tzinfo=UTC)

    monthly = RecurringRule(
        cadence=RecurringRule.Cadence.MONTHLY,
        anchor_day=31,
        anchor_month=1,
    )
    assert next_due_date(monthly, date(2027, 1, 31)) == date(2027, 2, 28)
    assert next_due_date(monthly, date(2027, 2, 28)) == date(2027, 3, 31)

    yearly = RecurringRule(
        cadence=RecurringRule.Cadence.YEARLY,
        anchor_day=29,
        anchor_month=2,
    )
    assert next_due_date(yearly, date(2024, 2, 29)) == date(2025, 2, 28)
    assert next_due_date(yearly, date(2027, 2, 28)) == date(2028, 2, 29)

    custom = RecurringRule(
        cadence=RecurringRule.Cadence.CUSTOM,
        custom_interval_unit=RecurringRule.IntervalUnit.MONTH,
        custom_interval_count=2,
        anchor_day=31,
        anchor_month=1,
    )
    assert next_due_date(custom, date(2026, 1, 31)) == date(2026, 3, 31)


