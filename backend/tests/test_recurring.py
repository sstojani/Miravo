def test_recurring_sync_replay_state_commands_conflict_bootstrap_and_tombstone(
    user: User,
    client_for_user: Callable[[User, str], APIClient],
) -> None:
    client = client_for_user(user, "Valid-Test-Password-8274!")
    tracker = _tracker(client)
    account_id = _account(client, tracker["id"])
    groceries = Category.objects.get(tracker_id=tracker["id"], name="Groceries")
    rule_id = uuid4()
    payload = _sync_payload(
        rule_id,
        UUID(str(tracker["id"])),
        UUID(str(account_id)),
        groceries.id,
    )
    create_operation = _sync_operation(
        rule_id,
        payload,
        command="create",
        base_version=None,
    )
    created = _push(client, create_operation)
    assert created.status_code == 200, created.data
    result = created.data["results"][0]
    assert result["status"] == "accepted"
    assert result["representation"]["state"] == "active"
    assert result["server_version"] == 1
    replay = _push(client, create_operation)
    assert replay.data["results"][0]["status"] == "duplicate"
    assert RecurringRule.objects.filter(id=rule_id).count() == 1

    paused = _push(
        client,
        _sync_operation(rule_id, payload, command="pause", base_version=1),
    )
    pause_result = paused.data["results"][0]
    assert pause_result["status"] == "accepted"
    assert pause_result["representation"]["state"] == "paused"

    skipped = _push(
        client,
        _sync_operation(
            rule_id,
            payload,
            command="skip_next",
            base_version=pause_result["server_version"],
        ),
    )
    skip_result = skipped.data["results"][0]
    assert skip_result["status"] == "accepted"
    assert skip_result["representation"]["next_due_on"] == "2026-09-01"
    occurrence = RecurringOccurrence.objects.get(rule_id=rule_id)
    assert occurrence.state == RecurringOccurrence.State.SKIPPED

    stale_payload = {**payload, "amount_minor": 4_000, "account_amount_minor": 4_000}
    stale = _push(
        client,
        _sync_operation(rule_id, stale_payload, command="update", base_version=1),
    )
    assert stale.data["results"][0]["status"] == "conflict"
    assert stale.data["results"][0]["representation"]["amount_minor"] == 3_500

    bootstrap = client.get("/api/v1/sync/bootstrap?limit=500")
    assert bootstrap.status_code == 200, bootstrap.data
    assert [item["id"] for item in bootstrap.data["data"]["recurring_rules"]] == [str(rule_id)]
    assert bootstrap.data["data"]["recurring_occurrences"][0]["id"] == str(occurrence.id)

    current_version = RecurringRule.objects.get(id=rule_id).version
    deleted = _push(
        client,
        _sync_operation(rule_id, payload, command="delete", base_version=current_version),
    )
    delete_result = deleted.data["results"][0]
    assert delete_result["status"] == "accepted"
    assert delete_result["representation"]["deleted_at"] is not None
