def test_downtime_catchup_is_bounded_idempotent_and_does_not_rewrite_history(
    user: User,
    client_for_user: Callable[[User, str], APIClient],
) -> None:
    client = client_for_user(user, "Valid-Test-Password-8274!")
    tracker = _tracker(client)
    account_id = _account(client, tracker["id"])
    groceries = Category.objects.get(tracker_id=tracker["id"], name="Groceries")
    created = _create_rule(
        client,
        _rule_payload(tracker["id"], account_id, category_id=groceries.id),
    )
    rule_id = created.data["id"]
    through = datetime(2026, 4, 1, tzinfo=UTC)

    first = materialize_rule(rule_id, through=through, maximum=2)
    assert first.posted == 2
    assert first.remaining_due is True
    second = materialize_due_rules(through=through)
    assert second == {
        "rules_considered": 1,
        "posted": 1,
        "skipped": 0,
        "failed": 0,
        "remaining_due_rules": 0,
    }
    assert list(
        RecurringOccurrence.objects.filter(rule_id=rule_id)
        .order_by("due_on")
        .values_list("due_on", flat=True)
    ) == [date(2026, 1, 31), date(2026, 2, 28), date(2026, 3, 31)]
    transactions = Transaction.objects.filter(source=Transaction.Source.RECURRING).order_by(
        "occurred_at"
    )
    assert transactions.count() == 3
    assert len(set(transactions.values_list("id", flat=True))) == 3
    assert all(record.status == Transaction.Status.POSTED for record in transactions)
    assert all(record.allocations.get().amount_minor == 2_500 for record in transactions)
    assert materialize_due_rules(through=through)["posted"] == 0
    assert Transaction.objects.filter(source=Transaction.Source.RECURRING).count() == 3

    update = _rule_payload(
        tracker["id"],
        account_id,
        starts_on="2026-01-31",
        next_due_on="2026-04-30",
        category_id=groceries.id,
    )
    update.update(amount_minor=4_000, base_version=RecurringRule.objects.get(id=rule_id).version)
    response = client.put(f"/api/v1/recurring-rules/{rule_id}/", update, format="json")
    assert response.status_code == 200, response.data
    assert set(transactions.values_list("amount_minor", flat=True)) == {2_500}


def test_pause_skip_resume_end_and_failed_occurrence_recovery(
    user: User,
    client_for_user: Callable[[User, str], APIClient],
) -> None:
    client = client_for_user(user, "Valid-Test-Password-8274!")
    tracker = _tracker(client)
    account_id = _account(client, tracker["id"])
    created = _create_rule(
        client,
        _rule_payload(tracker["id"], account_id, starts_on="2026-08-01"),
    )
    rule_id = created.data["id"]
    paused = client.post(
        f"/api/v1/recurring-rules/{rule_id}/pause/",
        {"base_version": created.data["version"]},
        format="json",
    )
    assert paused.status_code == 200, paused.data
    assert materialize_rule(rule_id, through=datetime(2026, 9, 1, tzinfo=UTC)).posted == 0

    skipped = client.post(
        f"/api/v1/recurring-rules/{rule_id}/skip-next/",
        {"base_version": paused.data["version"]},
        format="json",
    )
    assert skipped.status_code == 200, skipped.data
    assert skipped.data["state"] == "skipped"
    assert skipped.data["occurrence_key"] == occurrence_key(
        RecurringRule.objects.get(id=rule_id).id, date(2026, 8, 1)
    )
    rule = RecurringRule.objects.get(id=rule_id)
    resumed = client.post(
        f"/api/v1/recurring-rules/{rule_id}/resume/",
        {"base_version": rule.version},
        format="json",
    )
    assert resumed.status_code == 200, resumed.data
    result = materialize_rule(rule.id, through=datetime(2026, 9, 2, tzinfo=UTC))
    assert result.posted == 1
    assert RecurringOccurrence.objects.filter(rule_id=rule_id, state="skipped").count() == 1

    rule.refresh_from_db()
    ended = client.post(
        f"/api/v1/recurring-rules/{rule_id}/end/",
        {"base_version": rule.version},
        format="json",
    )
    assert ended.status_code == 200
    assert ended.data["state"] == "ended"
    assert ended.data["renewal_date"] is None

    failing = _create_rule(
        client,
        _rule_payload(tracker["id"], account_id, starts_on="2026-10-01"),
    )
    account = Account.objects.get(id=account_id)
    account.archived_at = datetime(2026, 9, 1, tzinfo=UTC)
    account.save(update_fields=("archived_at", "updated_at"))
    failure = materialize_rule(failing.data["id"], through=datetime(2026, 10, 2, tzinfo=UTC))
    assert failure.failed == 1
    failed_occurrence = RecurringOccurrence.objects.get(rule_id=failing.data["id"])
    assert failed_occurrence.state == "failed"
    assert failed_occurrence.error_code == "materialization_validation_error"
    assert failed_occurrence.transaction is None
    failed_id = failed_occurrence.id

    account.archived_at = None
    account.save(update_fields=("archived_at", "updated_at"))
    recovered = materialize_rule(failing.data["id"], through=datetime(2026, 10, 2, tzinfo=UTC))
    assert recovered.posted == 1
    failed_occurrence.refresh_from_db()
    assert failed_occurrence.id == failed_id
    assert failed_occurrence.state == "posted"
    assert failed_occurrence.version == 2


